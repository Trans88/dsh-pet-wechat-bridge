// Rebuild the checked-in Framework bundle; normal users never need this step.
import { build } from 'esbuild';
import { execFileSync } from 'node:child_process';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const commit = '8df84780f2aa1298f3b30965cdae143e049f3c8e'; // Live2D Cubism 5 SDK R4
const checkout = resolve(process.argv[2] || '../cubism-framework');
if (execFileSync('git', ['rev-parse', 'HEAD'], { cwd: checkout, encoding: 'utf8' }).trim() !== commit) throw new Error(`请使用官方 CubismWebFramework ${commit}。`);
const modules = {
  'live2dcubismframework': ['CubismFramework', 'Option', 'LogLevel'],
  'model/cubismusermodel': ['CubismUserModel'],
  'cubismmodelsettingjson': ['CubismModelSettingJson'],
  'effect/cubismeyeblink': ['CubismEyeBlink'],
  'effect/cubismbreath': ['CubismBreath', 'BreathParameterData'],
  'type/csmvector': ['csmVector'],
  'math/cubismmatrix44': ['CubismMatrix44'],
  'motion/acubismmotion': ['ACubismMotion'],
  'rendering/cubismrenderer': ['CubismRenderer'],
};
await build({ stdin: { contents: Object.entries(modules).map(([file, names]) => `export { ${names.join(', ')} } from './src/${file}';`).join('\n'), resolveDir: checkout },
  outfile: fileURLToPath(new URL('../web/vendor/live2d/framework.js', import.meta.url)), bundle: true, format: 'esm', target: 'es2022', supported: { 'template-literal': false }, minify: true,
  banner: { js: `/* Live2D Cubism Web Framework 5-r.4 (${commit}). Copyright Live2D Inc.\n * Live2D Open Software License: https://www.live2d.com/eula/live2d-open-software-license-agreement_en.html\n * Generated by scripts/build-cubism.mjs; see NOTICE.txt. */` }, legalComments: 'inline' });
