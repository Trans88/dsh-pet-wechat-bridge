import test from 'node:test';
import assert from 'node:assert/strict';
import { cpSync, mkdirSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { chromium } from 'playwright';
import { Config } from '../pet/config.mjs';
import { Store } from '../pet/store.mjs';
import { PetCore } from '../pet/core.mjs';
import { createPetServer } from '../pet/server.mjs';

test('real Chromium presents care phases, expanded stickers, interruption and desktop sheet changes', { skip: process.env.PET_BROWSER_TEST !== '1', timeout: 45000 }, async t => {
  const root=mkdtempSync(join(tmpdir(),'care-browser-')); cpSync(new URL('../web',import.meta.url),join(root,'web'),{recursive:true});
  const config=new Config(root),store=new Store(root),models={complete:async()=> '模拟回复'};
  const core=new PetCore(config,store,models),app=createPetServer({root,config,store,models,core});
  await new Promise(resolve=>app.server.listen(0,'127.0.0.1',resolve));
  const origin=`http://127.0.0.1:${app.server.address().port}`; let browser;
  t.after(async()=>{await browser?.close();app.abort();app.server.closeAllConnections();await new Promise(resolve=>app.server.close(resolve));store.close();rmSync(root,{recursive:true,force:true});});
  browser=await chromium.launch({headless:true}); const page=await browser.newPage({viewport:{width:1280,height:900}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(origin);await page.locator('[data-interaction="feed"]').click();
  await page.waitForFunction(()=>document.querySelector('#pet-character').dataset.careStep==='1');
  assert.ok(await page.locator('#pet-sprite-sheet').evaluate(img=>img.complete&&img.naturalWidth===1448));
  mkdirSync('dist/care-qa',{recursive:true});await page.screenshot({path:'dist/care-qa/feed.png'});
  await page.waitForFunction(()=>!document.querySelector('#pet-character').dataset.careAction);
  assert.equal(await page.locator('#pet-sprite-sheet').getAttribute('src'),'/assets/taolinghu-hd.png');
  await page.locator('[data-interaction="hug"]').click();await page.waitForFunction(()=>document.querySelector('#pet-character').dataset.careAction==='hug');
  await page.locator('[data-page="channels"]').click();assert.equal(await page.locator('#pet-character').getAttribute('data-care-action'),'');
  assert.equal(await page.locator('#sticker-pack img').count(),13);
  await page.setViewportSize({width:390,height:844});await page.locator('#sticker-pack').scrollIntoViewIfNeeded();
  await page.screenshot({path:'dist/care-qa/stickers-narrow.png'});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await page.goto(origin+'/desktop');await page.setViewportSize({width:320,height:470});
  await page.waitForTimeout(1300);await page.locator('#pet-character').press('Enter');
  await page.waitForFunction(()=>document.querySelector('#pet-character').dataset.careStep==='1');
  assert.equal(await page.locator('#pet-sprite-sheet').getAttribute('data-columns'),'4');
  await page.screenshot({path:'dist/care-qa/desktop-care.png'});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.waitForFunction(()=>!document.querySelector('#pet-character').dataset.careAction);
  assert.equal(await page.locator('#pet-sprite-sheet').getAttribute('src'),'/assets/taolinghu-hd.png');
  assert.deepEqual(errors,[]);
});
